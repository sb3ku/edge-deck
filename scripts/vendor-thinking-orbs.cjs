'use strict';
// Regenerates src/vendor/thinking-orbs.js from an unpacked thinking-orbs npm
// package (MIT, Jakub Antalik). The engine chunk is copied unchanged inside a
// function scope; only its trailing ES export list is replaced by a frozen
// global, because the dashboard loads plain scripts without a bundler.
//   npm pack thinking-orbs@0.3.2 && tar -xzf thinking-orbs-0.3.2.tgz
//   node scripts/vendor-thinking-orbs.cjs <path-to>/package
const fs = require('node:fs');
const path = require('node:path');

const packageDir = process.argv[2];
if (!packageDir) { console.error('Usage: node scripts/vendor-thinking-orbs.cjs <unpacked package directory>'); process.exit(1); }
const manifest = JSON.parse(fs.readFileSync(path.join(packageDir, 'package.json'), 'utf8'));
if (manifest.name !== 'thinking-orbs') throw new Error('Not the thinking-orbs package.');
const engineEntry = fs.readFileSync(path.join(packageDir, 'dist', 'engine.es.js'), 'utf8');
const chunkName = /from "\.\/(index-[A-Za-z0-9_-]+\.js)"/.exec(engineEntry)?.[1];
if (!chunkName) throw new Error('Engine chunk not found.');
const chunk = fs.readFileSync(path.join(packageDir, 'dist', chunkName), 'utf8');
if (/^\s*import\s/m.test(chunk)) throw new Error('Engine chunk has imports; update this script.');
const exportStart = chunk.lastIndexOf('\nexport {');
if (exportStart < 0) throw new Error('Engine export list not found.');
const exported = new Map([...chunk.slice(exportStart).matchAll(/(\w+) as (\w+)/g)].map(match => [match[1], match[2]]));
for (const name of ['MODE_FRAMES', 'paintFrame', 'resolvePreset', 'STATE_TO_MODE']) {
  if (!exported.has(name)) throw new Error(`Engine does not export ${name}.`);
}
const output = `/* thinking-orbs ${manifest.version} engine — MIT © Jakub Antalik
 * https://github.com/Jakubantalik/thinking-orbs (license: vendor/thinking-orbs-LICENSE.txt)
 * Generated by scripts/vendor-thinking-orbs.cjs: the published engine code is
 * unchanged; its ES export list is replaced by window.ThinkingOrbsEngine. */
(() => {
'use strict';
${chunk.slice(0, exportStart)}
window.ThinkingOrbsEngine = Object.freeze({ MODE_FRAMES, paintFrame, resolvePreset, STATE_TO_MODE, version: ${JSON.stringify(manifest.version)} });
})();
`;
const target = path.join(__dirname, '..', 'src', 'vendor');
fs.mkdirSync(target, { recursive: true });
fs.writeFileSync(path.join(target, 'thinking-orbs.js'), output);
fs.copyFileSync(path.join(packageDir, 'LICENSE'), path.join(target, 'thinking-orbs-LICENSE.txt'));
console.log(`Vendored thinking-orbs ${manifest.version} (${output.length} bytes).`);
